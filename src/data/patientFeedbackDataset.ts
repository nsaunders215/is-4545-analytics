// Combine base comments and generate realistic corpus up to ~110 records
export function getInitialFeedbackDataset(): PatientComment[] {
  const combined = [...INITIAL_PATIENT_FEEDBACK];
  let idCounter = 1041;

  for (let i = 0; i < 7; i++) {
    for (const t of ADDITIONAL_TEMPLATES) {
      const dateOffset = (i * 3 + (idCounter % 5));
      const d = new Date(2026, 9, Math.max(1, 25 - dateOffset));
      const dateStr = d.toISOString().split('T')[0];

      // slight variation in wait times and ratings
      const waitVar = Math.max(5, t.wait + ((idCounter % 5) - 2) * 10);
      const scoreVar = Math.max(1, Math.min(5, t.score + (idCounter % 3 === 0 ? 1 : 0) - (idCounter % 5 === 0 ? 1 : 0)));

      combined.push({
        id: `FB-${idCounter}`,
        date: dateStr,
        patientId: `PT-${3000 + idCounter}`,
        serviceLine: t.serviceLine,
        visitType: t.visitType,
        patientPersona: t.persona,
        satisfactionScore: scoreVar,
        communicationRating: Math.max(1, Math.min(5, t.comm + (idCounter % 2 === 0 ? 0 : (idCounter % 4 === 0 ? -1 : 1)))),
        followUpCompliant: scoreVar >= 4 ? true : (idCounter % 2 === 0),
        waitTimeMinutes: waitVar,
        commentText: t.text,
        sentiment: scoreVar >= 4 ? 'Positive' : (scoreVar === 3 ? 'Neutral' : 'Negative'),
        primaryTheme: t.theme,
        keywords: [...t.keywords],
        issueCategories: [...t.issues],
      });
      idCounter++;
    }
  }

  return combined;
}

